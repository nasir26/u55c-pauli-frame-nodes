#!/bin/bash
# Builds submission/ and the submission zip from the manuscript sources.
# Author: Nasir Ali, C-DAC Noida.
#   manuscript/        flattened manuscript.tex (sections and generated tables inlined), class, style, references.bib,
#                      figures, compiled manuscript.pdf (rebuilt from these files alone)
#   cover_letter.pdf
# Refuses to build with PENDING markers, undefined references, dashes in prose, uncited or unverified references.
set -euo pipefail
P=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
REPO=$(cd "$P/.." && pwd)
PY=$REPO/../envs/stim/bin/python
export PATH=$REPO/../envs/texlive/bin/x86_64-linux:$PATH
cd $P
$PY scripts/make_bib.py
STIM_BUILD=hw_tf $PY scripts/make_numbers.py
$PY scripts/make_figures.py > /dev/null
python3 scripts/lint_dashes.py main.tex sections/*.tex cover_letter.tex

S=$P/submission; rm -rf $S; mkdir -p $S/manuscript/figures
python3 - "$S/manuscript/manuscript.tex" <<'PYEOF'
import os, re, sys
def expand(path):
    s = open(path).read()
    def rep(m):
        f = m.group(1) if m.group(1).endswith(".tex") else m.group(1) + ".tex"
        if not os.path.exists(f):
            return m.group(0)
        body = "\n".join(l for l in expand(f).splitlines() if not l.startswith("% generated by"))
        return body.strip("\n")
    return re.sub(r"\\input\{([^}]*)\}", rep, s)
out = expand("main.tex").replace("\\newcommand{\\PENDING}[1]{\\textcolor{red}{[PENDING: #1]}}\n", "")
assert "PENDING" not in out, "PENDING markers left in the manuscript"
open(sys.argv[1], "w").write(out)
PYEOF
cp sn-jnl.cls sn-mathphys-num.bst references.bib $S/manuscript/
for f in $(grep -ho "includegraphics\[[^]]*\]{[^}]*}" $S/manuscript/manuscript.tex | sed 's/.*{//; s/}//' | sort -u); do
  cp $f $S/manuscript/figures/; done
cd $S/manuscript
latexmk -pdf -interaction=nonstopmode -halt-on-error manuscript.tex > /dev/null 2>&1 || { tail -30 manuscript.log; exit 1; }
und=$(grep -c "undefined" manuscript.log || true); err=$(grep -c "^!" manuscript.log || true)
echo "manuscript: $und undefined, $err errors, $(pdfinfo manuscript.pdf | awk '/Pages/{print $2}') pages"
[ "$und" = 0 ] && [ "$err" = 0 ] || exit 1
# every cited key is in references.bib and verified (or one of the documented manual entries)
python3 - <<'PYEOF'
import re
aux = open("manuscript.aux").read()
cited = sorted({k.strip() for m in re.findall(r"\\citation\{([^}]*)\}", aux) for k in m.split(",")})
bib = set(re.findall(r"@\w+\{([^,]+),", open("references.bib").read()))
rep = open("../../refs/verification_report.md").read()
ok = set(re.findall(r"\|\s*(\w+)\s*\|\s*PASS\s*\|", rep)) | set(re.findall(r"\|\s*(\w+)\s*\|\s*MANUAL\s*\|", rep))
missing = [k for k in cited if k not in bib]
unver = [k for k in cited if k not in ok]
uncited = sorted(bib - set(cited))
print(f"references: {len(cited)} cited, {len(missing)} missing, {len(unver)} unverified, {len(uncited)} in bib but not cited {uncited}")
assert not missing and not unver
PYEOF
rm -f manuscript.aux manuscript.log manuscript.out manuscript.fls manuscript.fdb_latexmk manuscript.blg
cd $P
mkdir -p $S/cover_build; cp cover_letter.tex generated/macros.tex $S/cover_build/; mkdir -p $S/cover_build/generated
cp generated/macros.tex $S/cover_build/generated/
(cd $S/cover_build && latexmk -pdf -interaction=nonstopmode -halt-on-error cover_letter.tex > /dev/null 2>&1) || exit 1
grep -q PENDING <(pdftotext $S/cover_build/cover_letter.pdf -) && { echo "PENDING in cover letter"; exit 1; }
cp $S/cover_build/cover_letter.pdf $S/cover_letter_to_editor.pdf; rm -rf $S/cover_build
Z=$P/stim_u55c_four_nodes_submission.zip; rm -f $Z
(cd $P && zip -qr $Z submission)
sha256sum $Z > $Z.sha256
unzip -l $Z | tail -1
